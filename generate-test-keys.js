// ============================================================================
// generate-test-keys.js — تولید کلیدهای تستی برای اتصال سامانه مودیان
// ============================================================================
// نحوه اجرا (در ترمینال پروژه):
//   node generate-test-keys.js
//
// خروجی: یک فایل moidian-test-credentials.txt با تمام مقادیر مورد نیاز
// ============================================================================

const crypto = require('crypto')
const fs = require('fs')
const path = require('path')

console.log('در حال تولید کلیدهای تستی برای سامانه مودیان...\n')

// ۱. تولید جفت کلید RSA
const { publicKey, privateKey } = crypto.generateKeyPairSync('rsa', {
  modulusLength: 2048,
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
})

// ۲. تولید Client ID و Client Secret
const clientId = crypto.randomUUID()
const clientSecret = crypto.randomBytes(32).toString('hex')

// ۳. شناسه مالیاتی و کد اقتصادی تستی
const fiscalId = '14001234567'  // ۱۱ رقم تستی
const economicCode = '123456789012'  // ۱۲ رقم تستی

// ۴. ساخت محتوای فایل خروجی
const content = `=============================================================
  Credentials تستی برای اتصال سامانه مودیان
=============================================================

تاریخ تولید: ${new Date().toLocaleString('fa-IR')}

⚠️  هشدار: این کلیدها فقط برای تست سیستم هستند.
   در محیط production، حتماً از کلیدهای واقعی سامانه مودیان استفاده کنید.

-------------------------------------------------------------
۱. شناسه مالیاتی (۱۱ رقم)
-------------------------------------------------------------
${fiscalId}

-------------------------------------------------------------
۲. کد اقتصادی (۱۲ رقم) — اختیاری
-------------------------------------------------------------
${economicCode}

-------------------------------------------------------------
۳. Client ID (شناسه کلاینت)
-------------------------------------------------------------
${clientId}

-------------------------------------------------------------
۴. Client Secret (رمز کلاینت)
-------------------------------------------------------------
${clientSecret}

-------------------------------------------------------------
۵. Private Key (کلید خصوصی) — کل این بخش را کپی کنید
-------------------------------------------------------------
${privateKey}-------------------------------------------------------------

✅ راهنمای استفاده:
   ۱. فایل settings-page.tsx در پروژه → تب «مودیان»
   ۲. فیلدهای بالا را دقیقاً به همین شکل در فرم وارد کنید
   ۳. محیط را روی «محیط تست (Sandbox)» تنظیم کنید
   ۴. «ارسال خودکار فاکتورها» را فعلاً غیرفعال کنید
   ۵. دکمه «ذخیره و تست اتصال» را بزنید

📋 نتیجه مورد انتظار:
   - ذخیره در دیتابیس: ✅ موفق
   - تست اتصال به مودیان: ❌ ناموفق (طبیعی است — چون credentials واقعی نیستند)
   - این یعنی سیستم درست کار می‌کند

=============================================================
`

// ۵. نوشتن در فایل
const outputPath = path.join(__dirname, 'moidian-test-credentials.txt')
fs.writeFileSync(outputPath, content, 'utf8')

console.log('✅ کلیدهای تستی با موفقیت تولید شدند!')
console.log(`📄 فایل خروجی: ${outputPath}`)
console.log('\nاین فایل را باز کنید و مقادیر را در فرم مودیان کپی کنید.')
console.log('\n⚠️  این فایل را در production استفاده نکنید — فقط برای تست است.')
